// Build question objects with stable ids (A1, A2, ... per domain).
const counters = {};
export const QUESTIONS = [...Q1, ...Q2].map(([d, q, o, a, w]) => {
  counters[d] = (counters[d] || 0) + 1;
  return { id: `${d}${counters[d]}`, d, q, o, a, w };
});
export const QUESTION = Object.fromEntries(QUESTIONS.map((q) => [q.id, q]));
export const questionsByDomain = (d) => QUESTIONS.filter((q) => q.d === d);

